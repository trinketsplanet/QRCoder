    private static void Generate(string fileName, string payload, string icon)
    {
        using var qrGenerator = new QRCodeGenerator();
        using var qrData = qrGenerator.CreateQrCode(payload, QRCodeGenerator.ECCLevel.M);
        var svgQrCode = new TPSvgQrCode(qrData);
        string svg = svgQrCode.GetGraphic(
            pixelsPerModule: 10,
            darkColorHex: "#fee4e4",
            icon: icon);

        string outputFile = Path.Combine(Environment.CurrentDirectory, "QR", fileName);
        Directory.CreateDirectory(Path.GetDirectoryName(outputFile)!);
        File.WriteAllText(outputFile, svg);
        Console.WriteLine($"SVG QR code with rounded modules written to {outputFile}");
    }
